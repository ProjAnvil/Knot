// Command gen-ts generates TypeScript declarations for the models root
// package (github.com/ProjAnvil/knot/models) using tygo.
//
// The golden output is committed at models/ts/index.d.ts so frontend and
// MCP consumers can share the exact wire types, and so CI can fail when the
// declarations drift from the Go structs. Run from the repo root:
//
//	go run ./tools/cmd/gen-ts
package main

import (
	"fmt"
	"os"

	"github.com/gzuidhof/tygo/tygo"
)

const (
	// packageName is the only package generated. The gormbind subpackage is
	// intentionally excluded: it is a persistence concern, not a wire type.
	packageName = "github.com/ProjAnvil/knot/models"

	// outputPath is the golden file location, relative to the repo root.
	// tygo treats any path ending in ".ts" as a file path, so this writes
	// index.d.ts itself rather than index.ts inside the folder.
	outputPath = "models/ts/index.d.ts"

	// tygoHeader is the first line tygo always emits. It is replaced with
	// genHeader below so the file points at this wrapper, not the library.
	tygoHeader = "// Code generated by tygo. DO NOT EDIT.\n"

	// genHeader identifies the tool that owns regeneration of the golden.
	genHeader = "// Code generated by tools/cmd/gen-ts. DO NOT EDIT.\n"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "gen-ts: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	// The PackageConfig fields mirror tygo's YAML keys "path" and
	// "output_path". Building the config in Go keeps the single source of
	// truth inside this wrapper.
	config := &tygo.Config{
		Packages: []*tygo.PackageConfig{
			{
				Path:       packageName,
				OutputPath: outputPath,
				// "union" emits string-literal type aliases instead of
				// typed const declarations: const initializers with a
				// type annotation are not valid in a .d.ts ambient
				// context (tsc error TS1039).
				EnumStyle: "union",
			},
		},
	}

	if err := tygo.New(config).Generate(); err != nil {
		return fmt.Errorf("generate typescript: %w", err)
	}

	// tygo always leads the file with its own "Code generated by tygo"
	// line; swap it for the wrapper header so the committed golden points
	// at the command developers must run. Fail loudly if tygo ever changes
	// its header format.
	content, err := os.ReadFile(outputPath)
	if err != nil {
		return fmt.Errorf("read generated file: %w", err)
	}
	if len(content) < len(tygoHeader) || string(content[:len(tygoHeader)]) != tygoHeader {
		return fmt.Errorf("unexpected tygo output header in %s", outputPath)
	}
	headerless := content[len(tygoHeader):]
	out := append([]byte(genHeader), headerless...)
	if err := os.WriteFile(outputPath, out, 0o644); err != nil {
		return fmt.Errorf("write generated file: %w", err)
	}

	fmt.Printf("wrote %s\n", outputPath)
	return nil
}
